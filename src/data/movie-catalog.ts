function movie(
  title: string,
  director: string,
  year: number,
  wikiEn = "",
  extras: {
    aliases?: string[];
    providers?: string[];
    origin?: "jp" | "west";
  } = {}
) {
  return {
    type: "movie" as const,
    title,
    director,
    year,
    wikiEn,
    origin: extras.origin,
    aliases: extras.aliases,
    providers: extras.providers,
  };
}

const jp = (extra: { aliases?: string[]; providers?: string[] } = {}) => ({
  origin: "jp" as const,
  ...extra,
});
const west = (extra: { aliases?: string[]; providers?: string[] } = {}) => ({
  origin: "west" as const,
  ...extra,
});

